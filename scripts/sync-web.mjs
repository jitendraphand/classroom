/**
 * Copy the web app's pure modules (no React, no Node APIs) into
 * src/shared/web so the Windows app uses the same rules and constants:
 * poll intervals, search, share quality / video mode, student drawing.
 *
 *   node scripts/sync-web.mjs [path-to-classroom-repo]   (default ../classroom)
 *
 * tests/webSync.test.ts fails when a copy drifts from the web source (when
 * the classroom repo is checked out next to this one).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));

export const WEB_MODULES = ['pollPolicy.ts', 'peopleSearch.ts', 'videoQuality.ts', 'drawLogic.ts', 'eraseBatch.ts', 'deviceTakeover.ts', 'classFinish.ts', 'reconnectQuality.ts', 'whiteboard/model.ts', 'whiteboard/codec.ts', 'whiteboard/render.ts', 'whiteboard/session.ts', 'whiteboard/pdf.ts', 'whiteboard/WhiteboardBoard.tsx', 'whiteboard/flyout.ts', 'whiteboard/FlyoutBar.tsx', 'whiteboard/recognize.ts', 'whiteboard/icons.tsx', 'zoomPan.ts', 'audioPolicy.ts', 'micDuck.ts', 'realtimePackets.ts', 'clientError.ts', 'timeFormat.ts', 'rosterWindow.ts'];
export const HEADER = '// GENERATED by scripts/sync-web.mjs from classroom apps/web/src/lib. Do not edit here.\n';

const repo = path.resolve(process.argv[2] || path.join(here, '..', '..', 'classroom'));
const from = path.join(repo, 'apps/web/src/lib');
const to = path.join(here, '..', 'src/shared/web');
if (import.meta.url === `file://${process.argv[1]}`) {
  fs.mkdirSync(to, { recursive: true });
  for (const name of WEB_MODULES) {
    const src = fs.readFileSync(path.join(from, name), 'utf8');
    fs.mkdirSync(path.dirname(path.join(to, name)), { recursive: true });
    fs.writeFileSync(path.join(to, name), HEADER + src);
    console.log('synced', name);
  }
  const icons = iconsModule(fs.readFileSync(path.join(repo, 'apps/web/src/components/ui/Icons.tsx'), 'utf8'));
  fs.writeFileSync(path.join(to, 'icons.ts'), icons);
  console.log('synced icons.ts');
}

/** The web's React icon components → static SVG strings (same drawings). */
export function iconsModule(tsx) {
  const out = {};
  const re = /export function Icon(\w+)\(p: P\) \{\s*return \(\s*<svg \{\.\.\.base\(p\)\}>([\s\S]*?)<\/svg>/g;
  let m;
  while ((m = re.exec(tsx))) {
    const body = m[2]
      .replace(/\s+/g, ' ')
      .replace(/([a-z])([A-Z])(?=[a-z]*=)/g, (_, a, b) => `${a}-${b.toLowerCase()}`)
      .replace(/=\{(-?[\d.]+)\}/g, '="$1"')
      .replace(/> </g, '><')
      .trim();
    out[m[1]] = `<svg viewBox="0 0 24 24" fill="none" aria-hidden="true">${body}</svg>`;
  }
  return `${HEADER}// Icons from apps/web/src/components/ui/Icons.tsx as SVG strings.\nexport const WEB_ICONS = ${JSON.stringify(out, null, 2)} as const;\n`;
}
