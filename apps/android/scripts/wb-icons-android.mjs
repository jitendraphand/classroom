/**
 * Whiteboard tool icons for Android, generated from the web app's WB_ICONS
 * (apps/web/src/lib/whiteboard/icons.tsx) so every app shows the same
 * drawings. Run after the web icons change:
 *
 *   node apps/android/scripts/wb-icons-android.mjs [path-to-icons.tsx]
 *
 * Writes app/src/main/res/drawable/wb_<name>.xml (white; tinted at runtime).
 * WebParityTest fails when the drawables and the web icons differ.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(process.argv[2] || path.join(here, '../../web/src/lib/whiteboard/icons.tsx'), 'utf8');

export function parseIcons(text) {
  const start = text.indexOf('export const WB_ICONS = {');
  const end = text.indexOf('} satisfies', start);
  if (start < 0 || end < 0) throw new Error('WB_ICONS not found');
  const block = text.slice(start + 'export const WB_ICONS = '.length, end + 1);
  const ring = (cx, cy, r) => `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`;
  return new Function('ring', `return (${block});`)(ring);
}

const snake = (s) => s.replace(/[A-Z]/g, (c) => '_' + c.toLowerCase());
const icons = parseIcons(src);
const out = path.join(here, '../app/src/main/res/drawable');
for (const [name, def] of Object.entries(icons)) {
  const paths = def.d
    .map((d) =>
      def.fill
        ? `    <path android:pathData="${d}" android:fillColor="#FFFFFFFF" android:strokeColor="#FFFFFFFF" android:strokeWidth="1.5" android:strokeLineCap="round" android:strokeLineJoin="round" />`
        : `    <path android:pathData="${d}" android:fillColor="#00000000" android:strokeColor="#FFFFFFFF" android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round" />`
    )
    .join('\n');
  const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/wb-icons-android.mjs from web WB_ICONS.${name}. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
${paths}
</vector>
`;
  fs.writeFileSync(path.join(out, `wb_${snake(name)}.xml`), xml);
}
// Stamp of the web source block, checked by WebParityTest (icons out of date → regenerate).
const blockText = src.slice(src.indexOf('export const WB_ICONS = {'), src.indexOf('} satisfies') + 1);
const { createHash } = await import('node:crypto');
fs.writeFileSync(path.join(here, 'wb-icons.sha256'), createHash('sha256').update(blockText).digest('hex') + '\n');
console.log(`wrote ${Object.keys(icons).length} icons`);
