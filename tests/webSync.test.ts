import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { statePollMs, chatPollMs } from '../src/shared/web/pollPolicy';
import { filterMessages, filterPeople } from '../src/shared/web/peopleSearch';
import { shareProfile } from '../src/shared/web/videoQuality';

const HEADER = '// GENERATED by scripts/sync-web.mjs from classroom apps/web/src/lib. Do not edit here.\n';
const MODULES = ['pollPolicy.ts', 'peopleSearch.ts', 'videoQuality.ts', 'drawLogic.ts', 'whiteboard/model.ts', 'whiteboard/codec.ts', 'whiteboard/session.ts', 'realtimePackets.ts'];
const webLib = path.resolve(__dirname, '..', '..', 'classroom', 'apps', 'web', 'src', 'lib');

test('shared web modules are byte copies of the web app (run scripts/sync-web.mjs)', (t) => {
  if (!fs.existsSync(webLib)) {
    t.skip('classroom repo not checked out next to this one');
    return;
  }
  for (const name of MODULES) {
    const mine = fs.readFileSync(path.join(__dirname, '..', 'src', 'shared', 'web', name), 'utf8');
    const web = fs.readFileSync(path.join(webLib, name), 'utf8');
    assert.equal(mine, HEADER + web, `${name} drifted from the web app`);
  }
});

test('teacher poll intervals are the web values', () => {
  // Pushes (cls-state nudges, chat packets) drive refreshes; polls are 60 s safety nets (web 97b3bab).
  assert.equal(statePollMs({ role: 'teacher', hidden: true, pushLive: true }), 60000);
  assert.equal(statePollMs({ role: 'teacher', hidden: false, pushLive: false }), 2000);
  assert.equal(chatPollMs({ hidden: false, pushLive: true }), 60000);
  assert.equal(chatPollMs({ hidden: true, pushLive: true }), 60000);
  assert.equal(chatPollMs({ hidden: false, pushLive: false }), 6000);
});

test('search matches name or SID like the web roster and chat', () => {
  const people = [
    { displayName: 'Asha Rao', sid: 'S 1001' },
    { displayName: 'Ben Ali', sid: null },
  ];
  assert.deepEqual(filterPeople(people, 'asha').map((p) => p.displayName), ['Asha Rao']);
  assert.deepEqual(filterPeople(people, 's1001').map((p) => p.displayName), []);
  assert.deepEqual(filterPeople(people, '1001').map((p) => p.displayName), ['Asha Rao']);
  const msgs = [
    { senderName: 'Asha Rao', body: 'hello', recipientName: null },
    { senderName: 'Teacher', body: 'fractions today', recipientName: null },
  ];
  assert.equal(filterMessages(msgs, 'fraction').length, 1);
});

test('video mode is 720p / 24 fps, motion, keep resolution', () => {
  const p = shareProfile(true);
  assert.equal(p.capture.frameRate.max, 24);
  assert.equal(p.capture.height?.max, 720);
  assert.equal(p.contentHint, 'motion');
  assert.equal(p.degradationPreference, 'maintain-resolution');
});
